#!/usr/bin/env node
'use strict';
// Generates lib/ncaam-champ-crosswalk.json: NCAAM national champion futures, one row per team listed on BOTH
// Polymarket US (gateway /v2/leagues/cbb/events?type=futures -> cbb-champ-* event) and/or Kalshi (KXMARMAD),
// keyed by ESPN team id via lib/ncaab-d1.js. A contract whose team does not resolve to a D1 school is left out
// (reported as unmatched) and is therefore dropped at runtime. Public, keyless endpoints only.
// Usage: node scripts/gen-ncaam-champ-crosswalk.cjs
const fs = require('node:fs');
const path = require('node:path');
const { d1Team } = require('../lib/ncaab-d1');

const GW = 'https://gateway.polymarket.us';
const KALSHI = 'https://api.elections.kalshi.com/trade-api/v2';
const getJson = async (u) => { const r = await fetch(u, { headers: { accept: 'application/json' } }); if (!r.ok) throw new Error(`${r.status} ${u}`); return r.json(); };

(async () => {
  const list = await getJson(`${GW}/v2/leagues/cbb/events?type=futures&limit=100&active=true&closed=false`);
  const ev = (list.events || []).find((e) => /^cbb-champ-/.test(e.slug || '') && !e.closed);
  if (!ev) throw new Error('no open cbb-champ-* event on Polymarket US');
  const full = await getJson(`${GW}/v1/events/slug/${encodeURIComponent(ev.slug)}`);
  const pmEvent = full.event || full;
  const k = await getJson(`${KALSHI}/events?series_ticker=KXMARMAD&status=open&with_nested_markets=true`);
  const kMarkets = (k.events || []).flatMap((e) => e.markets || []);

  const rows = new Map();
  const unmatched = { polymarket: [], kalshi: [] };
  const row = (t) => {
    if (!rows.has(t.espnId)) rows.set(t.espnId, { espnId: t.espnId, name: t.display || t.location, location: t.location, kalshi: null, polymarket: null });
    return rows.get(t.espnId);
  };
  for (const m of pmEvent.markets || []) {
    const side = (m.marketSides || []).find((s) => s.long) || {};
    const team = side.team || {};
    const t = d1Team(team.safeName) || d1Team(team.name) || d1Team(`${team.name || ''} ${team.alias || ''}`);
    if (!t) { unmatched.polymarket.push({ slug: m.slug, name: team.name || null }); continue; }
    row(t).polymarket = { slug: m.slug, teamId: team.id != null ? String(team.id) : null, name: team.name || null };
  }
  for (const m of kMarkets) {
    const t = d1Team(m.yes_sub_title);
    if (!t) { unmatched.kalshi.push({ ticker: m.ticker, label: m.yes_sub_title || null }); continue; }
    row(t).kalshi = { ticker: m.ticker, label: m.yes_sub_title || null };
  }
  const out = {
    note: 'NCAAM national champion futures crosswalk (ESPN team id -> Polymarket US cbb-champ market slug + Kalshi KXMARMAD ticker). Generated by scripts/gen-ncaam-champ-crosswalk.cjs; teams not listed are dropped at runtime.',
    generatedAt: new Date().toISOString(),
    polymarketEvent: ev.slug,
    kalshiEvent: (k.events && k.events[0] && k.events[0].event_ticker) || null,
    unmatched,
    teams: [...rows.values()].sort((a, b) => a.name.localeCompare(b.name)),
  };
  fs.writeFileSync(path.join(__dirname, '..', 'lib', 'ncaam-champ-crosswalk.json'), `${JSON.stringify(out, null, 1)}\n`);
  const both = out.teams.filter((t) => t.kalshi && t.polymarket).length;
  console.log(`wrote ${out.teams.length} teams (${both} on both venues); unmatched poly=${unmatched.polymarket.length} kalshi=${unmatched.kalshi.length}`);
})().catch((e) => { console.error(e); process.exit(1); });
