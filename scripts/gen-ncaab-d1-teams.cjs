#!/usr/bin/env node
'use strict';
// Generates lib/ncaab-d1-teams.json (+ src/ncaabD1Teams.js, the same list as ESM): every NCAA Division I men's basketball team per ESPN's public API.
// Source 1: /teams?groups=50 (362 teams on Oct 30 2026). Source 2: the groups=50 scoreboard for the next
// N days, keeping only competitors that carry a conferenceId (D1 conference members). Reclassifying schools
// such as Queens, Lindenwood and Southern Indiana are missing from source 1 but carry a conferenceId in
// source 2. Opponents without a conferenceId (Fisk, Reinhardt, Bethesda ...) are NOT D1 and are excluded.
// Usage: node scripts/gen-ncaab-d1-teams.cjs [days=21]
const fs = require('node:fs');
const path = require('node:path');

const BASE = 'https://site.api.espn.com/apis/site/v2/sports/basketball/mens-college-basketball';
const days = Number(process.argv[2]) || 21;

function ymd(ms) {
  const p = {};
  new Intl.DateTimeFormat('en-US', { timeZone: 'America/New_York', year: 'numeric', month: '2-digit', day: '2-digit' })
    .formatToParts(new Date(ms)).forEach((x) => { p[x.type] = x.value; });
  return `${p.year}${p.month}${p.day}`;
}
const slim = (t) => ({
  espnId: String(t.id), abbr: String(t.abbreviation || '').toUpperCase(), location: t.location || '',
  short: t.shortDisplayName || '', display: t.displayName || '', name: t.name || '',
});

(async () => {
  const byId = new Map();
  const teams = await (await fetch(`${BASE}/teams?groups=50&limit=500`)).json();
  for (const { team } of teams.sports[0].leagues[0].teams) byId.set(String(team.id), slim(team));
  const fromList = byId.size;
  for (let d = 0; d < days; d += 1) {
    const body = await (await fetch(`${BASE}/scoreboard?groups=50&limit=500&dates=${ymd(Date.now() + d * 864e5)}`)).json();
    for (const e of body.events || []) {
      for (const c of (e.competitions && e.competitions[0] && e.competitions[0].competitors) || []) {
        const t = c.team || {};
        if (t.id && t.conferenceId && !byId.has(String(t.id))) byId.set(String(t.id), slim(t));
      }
    }
  }
  const out = {
    note: `NCAA D1 men's basketball teams from ESPN (teams?groups=50 = ${fromList}, plus conference members seen on the groups=50 scoreboard). Generated by scripts/gen-ncaab-d1-teams.cjs. A team not listed is treated as non-D1 (dropped).`,
    generatedAt: new Date().toISOString(),
    teams: [...byId.values()].sort((a, b) => a.location.localeCompare(b.location)),
  };
  fs.writeFileSync(path.join(__dirname, '..', 'lib', 'ncaab-d1-teams.json'), `${JSON.stringify(out, null, 1)}\n`);
  // Same list as an ES module for the browser bundle (src/ncaabD1.js); never require() CJS from src/.
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'ncaabD1Teams.js'),
    `// GENERATED by scripts/gen-ncaab-d1-teams.cjs from ESPN. Do not edit by hand.\nexport const NCAAB_D1_TEAMS = ${JSON.stringify(out.teams)};\n`);
  console.log(`wrote ${out.teams.length} D1 teams (${fromList} from the team list)`);
})().catch((e) => { console.error(e); process.exit(1); });
