#!/usr/bin/env node
// Copies the canonical NCAAB team table from combo-worker (single source of truth, generated there by
// scripts/gen-ncaab-teams.js) into this repo, then regenerates the browser name map:
//   combo-worker ncaab-teams.json -> lib/ncaab-teams.json      (server resolver data)
//   combo-worker ncaab-teams.js   -> lib/ncaab-teams.js        (the SAME resolver, byte for byte)
//   -> src/ncaabTeamNames.js (ESM: every unambiguous known name -> ESPN id, for src/ncaabD1.js)
//   -> lib/ncaab-teams.sync.json (sha256 of both copied files + source ref; lib/ncaab-teams.test.js checks it)
// Usage: node scripts/sync-ncaab-teams.cjs [--from=/path/to/combo-worker] [--ref=main]   (default: GitHub via gh)
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');

const ROOT = path.join(__dirname, '..');
const arg = (k) => { const a = process.argv.find((x) => x.startsWith(`--${k}=`)); return a ? a.slice(k.length + 3) : null; };
const sha = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

function read(file) {
  const from = arg('from');
  if (from) return fs.readFileSync(path.join(from, file));
  const ref = arg('ref') || 'main';
  return execFileSync('gh', ['api', `repos/kevinfgordon1/combo-worker/contents/${file}?ref=${ref}`, '-H', 'Accept: application/vnd.github.raw'], { maxBuffer: 64 << 20 });
}

function browserNames(table, normName) {
  const ids = new Map();
  const add = (n, id) => { const k = normName(n); if (!k) return; if (!ids.has(k)) ids.set(k, new Set()); ids.get(k).add(id); };
  for (const t of table.teams) {
    for (const n of [t.location, t.short, t.display, `${t.location} ${t.mascot}`]) add(n, t.espnId);
    for (const a of Object.values(t.aliases || {})) for (const n of a.names || []) add(n, t.espnId);
  }
  const out = {};
  for (const [k, s] of [...ids].sort(([a], [b]) => a.localeCompare(b))) if (s.size === 1) out[k] = [...s][0];
  return out;
}

const json = read('ncaab-teams.json');
const js = read('ncaab-teams.js');
fs.writeFileSync(path.join(ROOT, 'lib', 'ncaab-teams.json'), json);
fs.writeFileSync(path.join(ROOT, 'lib', 'ncaab-teams.js'), js);
const table = JSON.parse(json);
delete require.cache[require.resolve('../lib/ncaab-teams.js')];
const { normName } = require('../lib/ncaab-teams.js');
const names = browserNames(table, normName);
fs.writeFileSync(path.join(ROOT, 'src', 'ncaabTeamNames.js'),
  `// GENERATED by scripts/sync-ncaab-teams.cjs from the canonical NCAAB team table (combo-worker ncaab-teams.json ${table.contentHash}). Do not edit by hand.\n`
  + `// Every unambiguous known venue spelling (normalized like lib/ncaab-teams.js normName) -> ESPN team id.\n`
  + `export const NCAAB_TABLE_HASH = ${JSON.stringify(table.contentHash)};\n`
  + `export const NCAAB_TEAM_NAMES = ${JSON.stringify(names)};\n`);
fs.writeFileSync(path.join(ROOT, 'lib', 'ncaab-teams.sync.json'), `${JSON.stringify({ source: 'kevinfgordon1/combo-worker', ref: arg('from') ? `local:${arg('from')}` : (arg('ref') || 'main'), contentHash: table.contentHash, generatedAt: table.generatedAt, jsonSha256: sha(json), jsSha256: sha(js) }, null, 1)}\n`);
console.log(`synced ncaab-teams ${table.contentHash}: ${table.teams.length} teams, ${Object.keys(names).length} browser names`);
