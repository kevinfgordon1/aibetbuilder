'use strict';
const assert = require('node:assert/strict');
delete process.env.MLB_ENABLED;
const { mlbOn, withoutMlb, isMlbKey } = require('./mlb-switch');
assert.equal(mlbOn({}), false);
assert.equal(mlbOn({ MLB_ENABLED: '1' }), true);
assert.equal(isMlbKey('baseball_mlb_world_series_winner'), true);
assert.equal(isMlbKey('basketball_nba'), false);
assert.deepEqual(withoutMlb(['baseball_mlb', 'americanfootball_nfl'], {}), ['americanfootball_nfl']);
assert.deepEqual(withoutMlb(['baseball_mlb', 'americanfootball_nfl'], { MLB_ENABLED: '1' }), ['baseball_mlb', 'americanfootball_nfl']);
const { FEATURED_SPORTS } = require('./odds-fetch-job');
assert.ok(!FEATURED_SPORTS.includes('baseball_mlb'), 'no MLB Odds API pulls by default');
const stub = (id, exports) => { const f = require.resolve(id); require.cache[f] = { id: f, filename: f, loaded: true, exports }; };
stub('./odds-shared', { supabase: {}, applyBookAdjustments: (x) => x });
const { _helpers } = require('../api/fetch-futures');
assert.ok(!_helpers.FUTURES_SPORTS.includes('baseball_mlb_world_series_winner'), 'no World Series futures by default');
assert.ok(_helpers.FUTURES_SPORTS.includes('basketball_ncaab_championship_winner'));
assert.ok(![...require('./underdog-lobby').INDEX_SPORTS].includes('MLB'), 'no Underdog MLB by default');
console.log('mlb-switch ok');
