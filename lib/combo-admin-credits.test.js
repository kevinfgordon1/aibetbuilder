const assert = require('assert');
const c = require('./combo-admin-credits');
const pend = c.pendingByUser([{ id: 'a', user_id: 'u', max_contracts: 45, fill_american: 100 }, { id: 'b', user_id: 'u', max_contracts: 10, fill_american: -150 }], [{ parlay_id: 'b', count: 10 }]);
assert.deepEqual(pend.u, { usd: 0.23, contracts: 45, locks: 1 });
const k = c.creditsFor({ fees_enabled: true, monthly_allowance_usd: 100, allowance_used_usd: 1.53, allowance_left_usd: 98.47, credits_usd: 5, can_quote: true }, pend.u);
assert.equal(k.left, 103.47); assert.equal(k.leftAfterPending, 103.24);
assert.deepEqual(c.creditsFor({ fees_enabled: false }), { feesEnabled: false });
const t = c.totals([{ credits: k }, { credits: { feesEnabled: false } }, { credits: null }]);
assert.equal(t.feeUsers, 1); assert.equal(t.exempt, 1); assert.equal(t.pending, 0.23);
console.log('comboAdminCredits ok');
